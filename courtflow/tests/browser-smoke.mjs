/* Browser smoke for the synthetic CourtFlow alpha. */
import assert from "node:assert/strict";
import fs from "node:fs/promises";
import {chromium} from "playwright";
const browser=await chromium.launch({headless:true,args:["--no-sandbox"]});
const page=await browser.newPage({viewport:{width:1440,height:900},acceptDownloads:true});
const errors=[];page.on("pageerror",e=>errors.push(String(e)));
try{
 await page.goto("http://127.0.0.1:8000/courtflow/",{waitUntil:"networkidle"});
 await page.locator(".cf-case-row").first().waitFor();
 assert.equal(await page.locator(".cf-case-row").count(),5,"Demo should have five cases");
 assert.equal(await page.locator("#metric-open").innerText(),"4");
 assert.equal(await page.locator("#metric-completed").innerText(),"1");
 assert.ok(Number(await page.locator("#metric-exceptions").innerText())>=1);
 await page.locator("#new-intake").click();
 await page.locator("#intake-form [name=title]").fill("Smoke test synthetic intake");
 await page.locator("#intake-form [name=profileId]").selectOption("records");
 await page.locator("#intake-form [name=receivedDate]").fill("2026-11-16");
 await page.locator("#intake-form [name=team]").selectOption("Operations");
 await page.locator("#intake-form [name=priority]").selectOption("Urgent");
 await page.locator("#intake-form [type=submit]").click();
 await page.getByRole("heading",{name:"Smoke test synthetic intake"}).waitFor();
 assert.equal(await page.locator(".cf-case-row").count(),6);
 assert.equal(await page.locator("#metric-open").innerText(),"5");
 await page.locator("[data-complete=register]").click();
 assert.ok((await page.locator("#case-detail").innerText()).includes("1 / 4"));
 await page.locator("#exception-form [name=note]").fill("Illustrative test discrepancy");
 await page.locator("#exception-form button[type=submit]").click();
 assert.ok((await page.locator("#case-detail").innerText()).includes("Illustrative test discrepancy"));
 await page.locator("[data-resolve]").click();
 assert.ok((await page.locator("#case-detail").innerText()).includes("Resolved"));
 const [download]=await Promise.all([page.waitForEvent("download"),page.locator("#export-json").click()]);
 const exported=JSON.parse(await fs.readFile(await download.path(),"utf8"));
 assert.equal(exported.cases.length,6);
 await page.reload({waitUntil:"networkidle"});
 assert.equal(await page.locator(".cf-case-row").count(),6,"Workspace should persist in local storage");
 await page.locator("#tab-studio").click();
 assert.equal(await page.locator(".cf-graph-node").count(),5,"Default petition graph should have five nodes");
 assert.ok(await page.locator("#designer-edges .cf-graph-edge").count()>=4,"Dependencies should be drawn as connectors");
 await page.locator("#designer-add").click();
 assert.equal(await page.locator(".cf-graph-node").count(),6,"New step should appear on the canvas");
 assert.equal(await page.locator("#designer-task-label").inputValue(),"New processing step");
 await page.locator("#designer-task-label").fill("Priority review");
 await page.locator("#designer-task-route").selectOption("Urgent");
 await page.locator("#designer-preview-priority").selectOption("Routine");
 assert.ok(await page.locator('[data-node="step_01"]').evaluate(node=>node.classList.contains("is-skipped")),"Nonmatching branch should be visibly skipped");
 await page.locator("#designer-preview-priority").selectOption("Urgent");
 const node=page.locator('[data-node="step_01"]');
 await node.scrollIntoViewIfNeeded();
 const beforeDrag=await page.locator('[data-node="step_01"]').evaluate(node=>node.style.left);
 const rect=await node.boundingBox();
 assert.ok(rect.y>=0&&rect.y+40<900,"Target must be visible for pointer drag.");
 await page.mouse.move(rect.x+60,rect.y+25);
 await page.mouse.down();
 await page.mouse.move(rect.x+130,rect.y+65,{steps:6});
 await page.mouse.up();
 const afterDrag=await page.locator('[data-node="step_01"]').evaluate(node=>node.style.left);
 assert.notEqual(beforeDrag,afterDrag,"Dragging should reposition a node");
 await page.locator("#designer-save").click();
 assert.ok((await page.locator("#notice").innerText()).includes("Workflow graph saved"));
 const storedProfile=await page.evaluate(()=>JSON.parse(localStorage.getItem("gkl.courtflow.workspace.v1")).profiles.find(p=>p.id==="petition"));
 assert.equal(storedProfile.tasks.find(t=>t.id==="step_01").when.priority,"Urgent");
 assert.ok(storedProfile.layout.step_01.x>=0);
 await page.reload({waitUntil:"networkidle"});
 await page.locator("#tab-studio").click();
 assert.equal(await page.locator(".cf-graph-node").count(),6,"Saved visual workflow should survive reload");
 await page.locator("#tab-audit").click();
 assert.ok(await page.locator("#audit-rows tr").count()>=6);
 const [csv]=await Promise.all([page.waitForEvent("download"),page.locator("#export-audit").click()]);
 assert.ok((await fs.readFile(await csv.path(),"utf8")).includes("Case reference"));
 assert.equal(errors.length,0,"No browser runtime errors expected: "+errors.join("; "));
 const mobile=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
 mobile.on("pageerror",e=>errors.push("mobile: "+String(e)));
 await mobile.goto("http://127.0.0.1:8000/courtflow/",{waitUntil:"networkidle"});
 await mobile.locator(".cf-case-row").first().waitFor();
 const sizes=await mobile.evaluate(()=>({vw:innerWidth,scroll:document.documentElement.scrollWidth}));
 assert.ok(sizes.scroll<=sizes.vw+4,"Mobile app should not overflow horizontally: "+JSON.stringify(sizes));
 await mobile.locator("#tab-studio").click();
 await mobile.locator(".cf-graph-node").first().waitFor();
 const canvas=await mobile.locator("#designer-viewport").evaluate(el=>({scrollWidth:el.scrollWidth,clientWidth:el.clientWidth}));
 assert.ok(canvas.scrollWidth>canvas.clientWidth,"Mobile workflow canvas should pan horizontally inside its region");
 assert.equal(errors.length,0,"No mobile page errors expected: "+errors.join("; "));
 await mobile.close();
}finally{await browser.close();}
console.log("CourtFlow browser smoke: PASS");
